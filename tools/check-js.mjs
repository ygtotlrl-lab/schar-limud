function runGate(gate) {
  return new Promise((resolve) => {
    /*  ⛔ השעון נפתח לפני ה-spawn — ⚠️ ההמתנה בתור הבריכה אינה
     *  זמן השער, ⛔ ומדידה שכוללת אותה הייתה תלויה במספר התהליכים. */
    const t0 = Date.now();
    /*  ⛔ `GATE_MUT` הוא מה שמפעיל את המוטציות בשער — ⚠️ הוא נשלח
     *  רק ברמה המלאה, ⛔ ובמפורש ריק ברמה המהירה: ⭐ סביבה שירשה אותו
     *  מהרצה קודמת הייתה מפעילה מוטציות ברמה שהצהירה שאינה מריצה אותן. */
    /*  ⛔ טווח הריצפה נמסר לשער המוכרז בלבד — ⚠️ שער שמספר
     *  טענותיו משתנה בין הרצות גם ברמה המהירה, ⭐ ומי שאינו מוכרז מקבל
     *  מחרוזת ריקה: ⛔ תקרה שווה לריצפה. */
    const _range = ((APP.floorRange || {})[gate.replace(/\.mjs$/, '')] || '').split(' — ')[0];
    const p = spawn(process.execPath, [join(ROOT, 'tools', gate)],
                    { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'],
                      env: { ...process.env, GATE_MUT: FULL ? '1' : '', GATE_FLOOR_RANGE: _range } });
    let out = '', err = '';
    p.stdout.on('data', (d) => { out += d; });
    p.stderr.on('data', (d) => { err += d; });
    p.on('error', (e) => resolve({ out, err: err + e.message + '\n', code: 1, ms: Date.now() - t0 }));
    p.on('close', (code) => resolve({ out, err, code, ms: Date.now() - t0 }));
  });
}

/*  ⛔ **סדר השיגור אינו סדר ההכרזה** — ⚠️ הבריכה נוטלת לפי
 *  סדר, ⭐ ושער ארוך שמוכרז בסופה מתחיל אחרון וקובע את הזנב:
 *  ⛔ נמדד — שער המטריצה הוכרז שבעים מתוך שבעים ושתיים, ⚠️ התחיל
 *  בשנייה 31 ורץ 78 — ⭐ והסט נגמר ב-109.5 אף שסך העבודה חלקי
 *  ארבעה הוא 71. ⛔ **והפלט נשאר בסדר ההכרזה** — ⚠️ `res` ממופתח
 *  במקום המקורי: ⭐ סדר לפי מי שסיים ראשון משתנה בין הרצה להרצה
 *  ושובר השוואת שני לוגים. ⚠️ **והמשקל הוא גודל המקור** — ⭐ מדד
 *  שנגזר מהעץ ⛔ ואינו רשימת זמנים מוקלדת: ⚠️ רשימה כזו מתיישנת
 *  בשקט ביום ששער תפח. */
async function runPool(list, jobs) {
  const res = new Array(list.length);
  const order = list.map((g, i) => i).sort((a, b) => size(list[b]) - size(list[a]));
  let next = 0;
  const worker = async () => {
    while (next < order.length) { const i = order[next++]; res[i] = await runGate(list[i]); }
  };
  await Promise.all(Array.from({ length: Math.min(jobs, list.length) }, worker));
  return res;
}
