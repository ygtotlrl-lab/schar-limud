  const SRCV = /\b(?:SRC|src|code|CODE|DOC|SETUP|SCHEMA|ymlSrc|shSrc)\b/;
  const ACALL = /(?:^|[^\w$.])(?:assert|ok|is|eq|t|T|check|noneIn|someIn)\s*\(/;
