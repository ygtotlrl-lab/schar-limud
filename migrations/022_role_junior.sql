-- ============================================================================
-- 022_role_junior.sql — דרגת `junior` נכנסת לאוצר המילים
-- ============================================================================
--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **`admin` · `manager` · `junior`, ואין רביעי:** ⚠️ אחת מארבע
--    האפליקציות מחזיקה מטריצת הרשאות עם שלוש דרגות, ⭐ **והנימוק:**
--    ⛔ אוצר מילים שנבדל בין האפליקציות הוא בדיוק מה שסבב 113 בא לסלק,
--    ⚠️ ובדיקה שהועתקה ביניהן משווה מול שם שאינו קיים ⛔ ונכשלת פתוח.
--
-- ⚠️ **והדרגה קיימת ואיש אינו נושא אותה כאן** — ⛔ אין באפליקציה הזו
--    מסך ניהול משתמשים, ⭐ ואין מסלול שמעניק אותה: ⛔ ההצהרה היא
--    האילוץ, ⚠️ והשער מודד שאין לה אתר בקוד.
--
-- ⛔ נכשל-סגור בכל מקרה: ⚠️ כל מה שאינו `admin` בדיוק אינו מקבל גישה,
--    ⭐ ולכן הרחבת האילוץ אינה מרחיבה הרשאה.
--
-- ⛔ אידמפוטנטית: ⚠️ האילוץ מוסר ונוצר מחדש באותו שם.
-- ============================================================================

alter table sl_users drop constraint if exists sl_users_role_check;

alter table sl_users
  add constraint sl_users_role_check
  check (role = any (array['admin'::text, 'manager'::text, 'junior'::text]));
