-- **הבעיה.** schar-limud הייתה היחידה מארבע האפליקציות עם **שכבת הרשאה
-- שנייה**: סיסמת `admin_pass` שיושבת ב-`sl_settings` ושומרת על מסך
-- ההגדרות, **מעל** הכניסה הרגילה. בהנהלה, בגיוס וביומן ההרשאה נגזרת
-- מהמשתמש שנכנס, ותו לא. שתי סיסמאות לאותו אדם אינן שכבת אבטחה נוספת —
-- הן מנגנון נפרד שצריך תחזוקה נפרדת.
--
-- ומעבר לאי-האחידות, המנגנון גרר **פרצה בהתקנה טרייה**: `slPassOf` נפלה
-- למחרוזת `'admin'` כשהשורה חסרה, ולכן מסד חדש שטרם נזרע בו `admin_pass`
-- נפתח לכל מי שהקליד «admin». הסכימה אמנם זרעה את השורה, אבל היא הייתה
-- הדבר היחיד שעמד בין ההתקנה לבין השער הפתוח.
--
-- **הפתרון.** ההרשאה נגזרת מהמשתמש, כמו בשלוש האחיות. העמודה כאן היא
-- מקור האמת היחיד לכך.
--
--   • `'admin'` — גישה מלאה, כולל מסך ההגדרות.
--   • כל ערך אחר (או `NULL` בשורה שנוצרה ידנית לפני המיגרציה) — משתמש
--     רגיל: רואה ורושם תשלומים, **אינו** נכנס להגדרות.
--
-- ⛔ **אין כאן CHECK על הערכים, במכוון.** המנהל יוצר ומנהל משתמשים
-- מלוח הבקרה של Supabase (אין באפליקציה מסך ניהול משתמשים), ו-CHECK היה
-- הופך שגיאת הקלדה בתפקיד ל-INSERT שנכשל. במקום זה **הקוד נכשל סגור**:
-- כל מה שאינו בדיוק `'admin'` אינו מקבל גישה להגדרות. תפקיד שהוקלד
-- בטעות שולל הרשאה — ולא מעניק אותה.
--
-- ⛔⛔ **אין DEFAULT — וזה שינוי מכוון מהניסוח הראשון של הסבב.** הגרסה
-- הראשונה של הקובץ הזה הגדירה `DEFAULT 'admin'`, מתוך שיקול נוח: במסד יש
-- משתמש אחד והוא המנהל, וברירת מחדל הייתה נותנת לו את התפקיד בלי UPDATE
-- על נתונים. **השיקול הזה נדחה**, משתי סיבות:
--
--   1. **זו הייתה החריגה היחידה בארגון.** ב-`ys_users` (הנהלה) העמודה
--      היא `text not null` **בלי DEFAULT**, וכך גם כאן מעכשיו. בגיוס יש
--      `DEFAULT`, אבל הוא `'manager'` — התפקיד ה**נמוך**. כלומר בשום
--      אפליקציה אחרת ברירת המחדל אינה **מעניקה** הרשאה.
--   2. **ברירת מחדל שמעניקה הרשאה היא בדיוק הכשל שהסבב הזה בא לסגור.**
--      משתמש חדש שנוצר בלי `role` היה מקבל גישה מלאה למסך ההגדרות בלי
--      שאיש החליט על כך — אותה משפחת כשל כמו `slPassOf` שנפלה ל-`'admin'`.
--      `DEFAULT 'user'` היה בטוח יותר, אבל עדיין סוטה מהדפוס: תפקיד הוא
--      החלטה, ולא ערך שנופל מאליו.
--
-- ⚠️ **המשמעות המעשית: יצירת משתמש חייבת לציין `role` במפורש** — INSERT
-- בלי העמודה הזו **נכשל במסד** (`null value in column "role"`), וזו
-- ההתנהגות הרצויה. שני הערכים:
--
--   INSERT INTO public.sl_users (username, password, role)
--   VALUES ('<שם>', '<שש ספרות>', 'admin');   -- גישה מלאה, כולל הגדרות
--
--   INSERT INTO public.sl_users (username, password, role)
--   VALUES ('<שם>', '<שש ספרות>', 'user');    -- משתמש רגיל
--
-- ⚠️ **שורת ה-UPDATE שלמטה היא הנגיעה היחידה בנתונים בקובץ הזה.** היא
-- ממלאת `'admin'` **רק** בשורות שקדמו לעמודה (`role IS NULL`) — כלומר
-- במסד הייצור: המשתמש היחיד, שהוא המנהל. שורה קיימת שכבר יש לה תפקיד
-- אינה נגעת. ⛔ בכל מסד אחר יש לבדוק את השורות **לפני** ההרצה: היא
-- מעניקה `'admin'` לכל מי שקדם למיגרציה.
--
-- אידמפוטנטית — אפשר להריץ שוב בבטחה (הרצה שנייה: העמודה כבר קיימת,
-- אין NULL-ים למלא, וה-NOT NULL/DROP DEFAULT הם no-op). אינה נוגעת
-- בסיסמאות, בטביעות או בכל נתון קיים אחר.
--
-- ⚠️ **סדר שלושת השלבים אינו ניתן לקיצור.** `ADD COLUMN … NOT NULL` בלי
-- DEFAULT **נכשל** על טבלה שיש בה שורות — Postgres אינו יכול למלא את
-- העמודה. לכן: מוסיפים nullable, ממלאים, ורק אז נועלים.
--
-- ✅ **מצב: הורצה ואומתה במסד הייצור** (השלמת סבב 26), כולל שלב 3 —
-- העמודה `NOT NULL` ו-`column_default = NULL`. הפסקה הבאה מתארת את מצב
-- הביניים, והיא רלוונטית להתקנה חדשה שטרם הריצה את הקובץ.
--
-- ⚠️ **עד שתורץ, מסך ההגדרות אינו נפתח לאיש** — וזו ההתנהגות הנכונה
-- (נכשל סגור). האפליקציה מזהה את המצב הזה ומציגה הודעה שאומרת זאת
-- במפורש, במקום «אין לך הרשאה» שהיה שולח את המנהל לחפש באג. שאר
-- האפליקציה — כניסה, תשלומים, תלמידים, דשבורד — אינה מושפעת כלל.
--
-- ⚠️ אין כאן GRANT חדש: ההרשאות ב-Postgres הן ברמת הטבלה, ו-`sl_users`
-- כבר מחזיקה `SELECT, INSERT, UPDATE, DELETE` ל-anon/authenticated/
-- service_role מ-000. עמודה חדשה בטבלה קיימת יורשת אותן. (כלל קריטי 3 —
-- GRANT מפורש + RLS — חל על **טבלה חדשה**, ואין כאן כזו.)
-- ============================================================

-- 1) הוספה כ-nullable ובלי DEFAULT (ר' האזהרה על סדר השלבים למעלה)
ALTER TABLE public.sl_users
  ADD COLUMN IF NOT EXISTS role TEXT;

-- 2) מילוי חד-פעמי לשורות שקדמו לעמודה — ורק להן
UPDATE public.sl_users SET role = 'admin' WHERE role IS NULL;

-- 3) נעילה: NOT NULL, ובלי DEFAULT כלל
ALTER TABLE public.sl_users ALTER COLUMN role SET NOT NULL;
ALTER TABLE public.sl_users ALTER COLUMN role DROP DEFAULT;

