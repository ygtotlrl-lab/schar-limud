-- 021_role_vocabulary_check.sql — אוצר מילים אחד לתפקיד
-- ============================================================================
--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **`admin` · `manager`, ואין שלישי:** ⚠️ שלוש האפליקציות שיש בהן
--    כניסה השוו כל אחת מול שם תפקיד משלה — ⭐ **הנימוק:** ⛔ שלושה
--    אוצרות מילים לאותו מושג הם שלוש הזדמנויות לטעות, ⚠️ ובדיקה
--    שהועתקה בין האפליקציות משווה מול שם שאינו קיים ⛔ ונכשלת פתוח.
--
-- ⚠️ **וכאן ההצהרה היא האילוץ עצמו** — ⛔ אין באפליקציה הזו מסך ניהול
--    משתמשים: ⭐ המנהל יוצר משתמש ב-`INSERT` ידני, ⚠️ ולכן השם היחיד
--    שהקוד נוקב בו הוא `admin`. ⛔ בלי האילוץ, `manager` היה שם שאיש
--    אינו אוכף — ⭐ ותפקיד שהוקלד בטעות היה יושב בעמודה בשקט.
--
-- ⛔ נכשל-סגור בכל מקרה: ⚠️ כל מה שאינו `admin` בדיוק אינו מקבל גישה,
--    ⭐ והאילוץ מונע את הכתיבה מלכתחילה.
--
-- ⛔ אידמפוטנטית: ⚠️ האילוץ מוסר ונוצר מחדש באותו שם.
-- ============================================================================

update sl_users
   set role = 'manager',
       updated_at = updated_at
 where role is not null and role <> '' and role <> 'admin';

alter table sl_users drop constraint if exists sl_users_role_check;

alter table sl_users
  add constraint sl_users_role_check
  check (role = any (array['admin'::text, 'manager'::text]));
