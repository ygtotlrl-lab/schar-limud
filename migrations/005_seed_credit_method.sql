-- ⚠️ **אין כאן שינוי סכימה** — זריעת נתון בלבד ל-sl_lists.
--
-- למה בכלל: תלמיד ששילם בשנה מסוימת מעבר לסך החיוב בטווח החודשים שלו
-- צובר יתרת זכות. כדי לנצל אותה בשנה הבאה רושמים לו תנועה רגילה
-- ב-sl_transactions עם payment_method = 'זוכה על חשבון יתרת זכות'.
-- התנועה מקטינה את חובו בדיוק כמו תשלום, אבל **אינה כסף שהתקבל**, ולכן
-- האפליקציה מוציאה אותה מכל סיכום גבייה/הכנסה (שורות "מזה זיכוי מיתרה"
-- ו"גבייה בפועל" בדשבורד, וגרף הגבייה).
--
-- למה davka אמצעי תשלום ולא sections: payment_method הוא השדה היחיד
-- שנשמר **על התנועה עצמה**. sl_lists.sections משמשת לשיוך תלמיד
-- (card_settings.section) ואין לה ייצוג ברמת התנועה — שימוש בה היה מחייב
-- עמודה חדשה ב-sl_transactions, כלומר שינוי סכימה שאינו נדרש.
--
-- ⚠️ המיגרציה הזו **אופציונלית**: האפליקציה זורעת את הפריט בעצמה
--    (ensureCreditMethod) בכניסה הראשונה אחרי סנכרון תקין, ובכל מקרה
--    מזריקה את האפשרות לטופס גם כשהפריט חסר. הקובץ קיים כדי שהזריעה
--    תהיה מתועדת ואפשרית גם ידנית.
--
-- הרצה חוזרת בטוחה — WHERE NOT EXISTS מונע כפילות (ל-sl_lists אין אילוץ
-- ייחודיות, ולכן ON CONFLICT DO NOTHING לא היה מספיק כאן).
-- ============================================================

INSERT INTO public.sl_lists (category, value)
SELECT 'payment_methods', 'זוכה על חשבון יתרת זכות'
WHERE NOT EXISTS (
  SELECT 1 FROM public.sl_lists WHERE value = 'זוכה על חשבון יתרת זכות'
);

-- ---------- אימות ----------
SELECT id, category, value
FROM public.sl_lists
WHERE value = 'זוכה על חשבון יתרת זכות';
-- מצופה: שורה אחת בדיוק, בקטגוריה payment_methods.
