-- ============================================================================
-- 015_users_drop_plaintext_password.sql — הסרת הסיסמה הגלויה מ-`sl_users`
-- ============================================================================
--
-- ⛔⛔ **נכתב ולא רץ.** ⛔ ההרצה היא פעולת מנהל, ⛔ ואין להריץ מתוך סשן.
--
-- ⭐ **מה שהוליד אותה:** `doLogin` השווה `.eq('password', p)` מול
--    העמודה הגלויה, כלומר היא הייתה **המפתח שפותח את הכניסה**. מפתח ה-anon
--    יושב ב-`index.html` הציבורי, ו-RLS כאן הוא `USING (true)` — כל מי
--    שקרא את קוד המקור יכול היה לשלוף את הסיסמה ולהיכנס בזהות של המנהל,
--    לאפליקציה שמנהלת **כספים**.
--
-- ⭐ **מה שכבר נעשה בקוד:** הכניסה המקוונת מאמתת מול
--    `pass_salt`+`pass_fp` דרך `slVerifyOffline` — אותו מסלול בדיוק כמו
-- הכניסה האופליין. ⚠️ לפני הכתיבה נבדק ש:
--    המשתמש היחיד ב-`sl_users` מחזיק מלח וטביעה באורך 64.
--
-- ═══ ⛔ הפער שנותר, ולמה צעד ב חסום ══════════════════════════════════════
-- ⛔ **אין כאן מסך ניהול משתמשים** — המנהל יוצר משתמש ב-`INSERT` ידני
--    ב-SQL Editor, כפי שקובץ ההתקנה מדגים. הטביעה נוצרה מאז ומתמיד
--    **בכניסה המקוונת הראשונה** (`slEnsurePassFp`), כלומר משתמש חדש נולד
--    בלי טביעה ובעל סיסמה גלויה בלבד.
--
-- ⚠️ **ולכן הסרה מלאה של העמודה כאן נועלת בחוץ כל משתמש עתידי:** לא ניתן
--    לחשב PBKDF2-SHA256 ב-100,000 סיבובים בתוך `INSERT` ידני, ואין מסלול
--    אחר ליצור טביעה. `SL_PLAINTEXT_BOOTSTRAP` שב-`index.html` הוא מה
--    שמחזיק את החלון הזה פתוח — השוואה מול הטקסט הגלוי **פעם אחת בחיי
--    המשתמש**, ורק כשאין לו טביעה כלל.
--
-- ⭐ **הטריגר לצעד ב:** מסלול יצירת-משתמש שגוזר טביעה בעצמו — מסך ניהול
--    משתמשים כמו בהנהלה וב-gius, או כלי עזר שמייצר `pass_salt`/`pass_fp`
--    להדבקה ב-`INSERT`. רק אחריו אפשר לכבות את `SL_PLAINTEXT_BOOTSTRAP`,
--    ורק אחרי זה למחוק את העמודה.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── צעד א — הסרת NOT NULL (אידמפוטנטי, בטוח להרצה מיידית) ──────────────────
-- ⚠️ בטוח כאן במיוחד: האפליקציה **אינה** יוצרת משתמשים כלל, ולכן אין מסלול
--    קוד שהאילוץ הזה מגן עליו.
alter table public.sl_users alter column password drop not null;

