-- ============================================================================
-- 020_settings_soft_delete.sql — `sl_settings` בצורת טבלת ההגדרות המשותפת
-- ============================================================================
--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ מוסיף ל-`sl_settings` את שלישיית המחיקה הרכה
--    — `deleted` · `deleted_at` · `deleted_by`.
--
-- ⛔⛔ **הנימוק:** ⚠️ ארבע טבלאות הגדרות בארבע צורות אינן ניתנות להצלבה,
--    ⭐ ו**מחיקת מפתח היא חותמת ולא היעדר**: ⛔ בלי השלישייה מפתח שנמחק
--    במכשיר אחד נראה לשני כ«אין לי», ⚠️ והוא מחזיר אותו.
--
-- ⚠️ **והעמודות נוספות בסוף** — ⛔ ולא באמצע: ⭐ סדר העמודות של טבלת
--    ההגדרות המשותפת הוא `key` · `value` · `updated_at` · `client_id`
--    ואז השלישייה, ⛔ והוספה בסוף היא בדיוק מה ששומר עליו.
--
-- ⛔ **נמדד לפני השינוי:** ⚠️ שורה אחת בטבלה.
-- ============================================================================

alter table public.sl_settings add column if not exists deleted    boolean not null default false;
alter table public.sl_settings add column if not exists deleted_at timestamptz;
alter table public.sl_settings add column if not exists deleted_by text;
