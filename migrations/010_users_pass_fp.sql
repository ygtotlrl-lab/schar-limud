-- **הבעיה.** `doLogin` שלח עד הסבב הזה שאילתה לענן
-- (`sl_users.select().eq('username').eq('password')`), ולכן **בלי רשת אי
-- אפשר היה להיכנס כלל**. מי שכבר נכנס פעם אחת המשיך לעבוד דרך `sl_session`,
-- אבל מכשיר שמישהו אחר נכנס בו אחרון נעל בחוץ את כל השאר. schar-limud
-- הייתה האחרונה מארבע האפליקציות שנשארה כך (hanhala פתרה בסבב 22, gius
-- בסבב 23) — וזאת בעוד **שאר** האפליקציה כאן עובדת אופליין במלואה מסבב 12.
--
-- **הפתרון.** לכל משתמש נשמרים `pass_salt` + `pass_fp`: טביעת
-- PBKDF2-SHA256 ב-100,000 סיבובים, עם **מלח אקראי פר-משתמש**. הטביעה
-- יורדת למכשיר; הסיסמה — לעולם לא. מכשיר שאבד חושף טביעות, לא סיסמאות,
-- וההשהיה של 100k היא מה שהופך ניחוש-בכוח על העותק שבדיסק ליקר גם מול
-- סיסמה בת שש ספרות (סבב 19).
--
-- ⛔ **`password` לא נגע.** הסיסמה נשארת טקסט גלוי בענן, במכוון: המנהל
-- חייב לראות ולנהל סיסמאות מתוך לוח הבקרה של Supabase (אין כאן מסך ניהול
-- משתמשים), וזו החלטה מתועדת (כלל ברזל 9). שתי העמודות שכאן **נוספות
-- לצידה** ואינן מחליפות אותה — תפקידן היחיד הוא האימות המקומי במכשיר,
-- שם הסיסמה עצמה אינה נשמרת לעולם.
--
-- ⚠️ אל תסיקו מכאן שהמסד עבר להצפנה. הוא לא.
--
-- אדיטיבית ואידמפוטנטית — אפשר להריץ שוב בבטחה, ואינה נוגעת בנתונים
-- קיימים. עד שתורץ, האפליקציה ממשיכה לעבוד בדיוק כמו קודם: משיכת
-- המשתמשים נופלת-חזרה לשתי עמודות (`slIsMissingFpCol`), ומסלול ההשלמה
-- מדלג בשקט — אבל **כניסה אופליין לא תעבוד**, כי אין ממה לגזור טביעה.
--
-- אחרי ההרצה, כניסה **מקוונת** אחת של כל משתמש משלימה את הטביעה שלו
-- (`slEnsurePassFp`), ומאותו רגע הוא יכול להיכנס באותו מכשיר בלי רשת.
--
-- ⚠️ אין כאן GRANT חדש: ההרשאות ב-Postgres הן ברמת הטבלה, ו-`sl_users`
-- כבר מחזיקה `SELECT, INSERT, UPDATE, DELETE` ל-anon/authenticated/
-- service_role מ-000. עמודה חדשה בטבלה קיימת יורשת אותן. (כלל קריטי 3 —
-- GRANT מפורש + RLS — חל על **טבלה חדשה**, ואין כאן כזו.)
-- ============================================================

ALTER TABLE public.sl_users
  ADD COLUMN IF NOT EXISTS pass_salt TEXT,
  ADD COLUMN IF NOT EXISTS pass_fp   TEXT;

